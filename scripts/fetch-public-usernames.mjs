/**
 * فاز ۱۲٫۳-م — اسنپشات نامهای کاربری برای صفحات ایستای پروفایل.
 *
 * ⚠️ خروجی استاتیک Next.js نمی‌تواند در زمان درخواست، مسیر دلخواه
 *    `/panel/<username>` را بسازد. بنابراین فهرست نامها هنگام بیلد از API
 *    عمومی خوانده می‌شود و در `generateStaticParams` استفاده می‌شود.
 * ⚠️ اگر API در CI در دسترس نبود، نسخهٔ قبلی نگه داشته می‌شود تا بیلد
 *    شکست نخورد و لینکهای موجود زنده بمانند.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUTPUT = fileURLToPath(
  new URL('../src/lib/generated/public-usernames.ts', import.meta.url),
);
const API_URL = 'https://api.arasanad.ir/api/v1/public/profiles';
const USERNAME_RE = /^[a-z][a-z0-9_]{1,30}[a-z0-9]$/;
const FALLBACK = ['mehdi_amouz'];

/** fetch فقط هدرها را پوشش می‌دهد؛ خواندن بدنه هم نیاز به مهلت جدا دارد. */
function withTimeout(promise, ms, label) {
  let timer;
  return Promise.race([
    promise,
    new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(`${label} timeout`)), ms);
    }),
  ]).finally(() => clearTimeout(timer));
}

function valid(list) {
  return (
    Array.isArray(list) &&
    list.length > 0 &&
    list.every((value) => typeof value === 'string' && USERNAME_RE.test(value))
  );
}

/** خواندن نسخهٔ ذخیرهشده به‌عنوان fallback امن. */
async function readSnapshot() {
  try {
    const source = await readFile(OUTPUT, 'utf8');
    // نباید با `[ ]` در عبارت `string[]` اشتباه شود؛ آرایه بعد از علامت `=` است.
    const match = source.match(/=\s*\[([\s\S]*?)\]\s*;/);
    if (!match) return FALLBACK;
    const parsed = JSON.parse(`[${match[1]}]`);
    return valid(parsed) ? parsed : FALLBACK;
  } catch {
    return FALLBACK;
  }
}

let usernames = await readSnapshot();
try {
  const response = await withTimeout(
    fetch(API_URL, { headers: { Accept: 'application/json' }, signal: AbortSignal.timeout(6000) }),
    6000,
    'fetch',
  );
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const payload = JSON.parse(await withTimeout(response.text(), 6000, 'body'));
  const fetched = payload?.data?.usernames;
  if (valid(fetched)) {
    // ادغام با اسنپشات قبلی: پاسخ ناقص API نباید مسیرهای موجود را حذف کند.
    const merged = [...usernames, ...fetched.map((value) => value.toLowerCase())];
    usernames = [...new Set(merged)].sort();
  } else {
    console.warn('[public-usernames] unexpected API payload; keeping committed snapshot');
  }
} catch (error) {
  console.warn(`[public-usernames] API unavailable, keeping committed snapshot: ${error.message}`);
}

const body = `/**
 * self-generated by scripts/fetch-public-usernames.mjs — ویرایش دستی نکنید.
 * فهرست نامهای کاربری دارای پروفایل عمومی برای ساخت مسیرهای ایستا.
 */
export const PUBLIC_USERNAMES: readonly string[] = ${JSON.stringify(usernames)};
`;

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, body, 'utf8');
console.log(`[public-usernames] wrote ${usernames.length} usernames to ${OUTPUT}`);
