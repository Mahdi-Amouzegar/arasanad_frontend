/**
 * فاز ۱۲٫۷ — اسنپشات کدهای پایدار پروفایل برای صفحات ایستا.
 *
 * خروجی استاتیک Next.js نمی‌تواند در زمان درخواست مسیر دلخواه
 * `/panel/<publicId>` بسازد؛ بنابراین فهرست هنگام بیلد از API عمومی خوانده
 * و با اسنپشات قبلی ادغام می‌شود. پاسخ ناقص یا قطع API نباید مسیر موجودی
 * را حذف کند.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUTPUT = fileURLToPath(
  new URL('../src/lib/generated/public-profiles.ts', import.meta.url),
);
const API_URL = 'https://api.arasanad.ir/api/v1/public/profiles';
const PUBLIC_ID_RE = /^[0-9a-f]{12}$/;
const USERNAME_RE = /^[a-z][a-z0-9_]{1,30}[a-z0-9]$/;
const FALLBACK = [
  { publicId: '6b08b2699e88', username: 'mehdi_amouz' },
  { publicId: '8a8d8879a02c', username: 'me_am_2' },
];

function withTimeout(promise, ms, label) {
  let timer;
  return Promise.race([
    promise,
    new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(`${label} timeout`)), ms);
    }),
  ]).finally(() => clearTimeout(timer));
}

function valid(list) {
  return (
    Array.isArray(list) &&
    list.length > 0 &&
    list.every((item) =>
      item &&
      typeof item === 'object' &&
      PUBLIC_ID_RE.test(String(item.publicId).toLowerCase()) &&
      USERNAME_RE.test(String(item.username).toLowerCase()))
  );
}

function normalize(list) {
  return list.map((item) => ({
    publicId: String(item.publicId).toLowerCase(),
    username: String(item.username).toLowerCase(),
  }));
}

async function readSnapshot() {
  try {
    const source = await readFile(OUTPUT, 'utf8');
    // نباید با `[ ]` در عبارت `Entry[]` اشتباه شود.
    const match = source.match(/PUBLIC_PROFILES[^=]*=\s*(\[[\s\S]*?\]);/);
    if (!match) return FALLBACK;
    const parsed = JSON.parse(match[1]);
    return valid(parsed) ? normalize(parsed) : FALLBACK;
  } catch {
    return FALLBACK;
  }
}

let profiles = await readSnapshot();
try {
  const response = await withTimeout(
    fetch(API_URL, { headers: { Accept: 'application/json' }, signal: AbortSignal.timeout(6000) }),
    6000,
    'fetch',
  );
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const payload = JSON.parse(await withTimeout(response.text(), 6000, 'body'));
  const fetched = payload?.data?.profiles;
  if (valid(fetched)) {
    const merged = new Map();
    for (const item of [...profiles, ...normalize(fetched)]) {
      const previous = merged.get(item.publicId);
      merged.set(item.publicId, {
        publicId: item.publicId,
        username: item.username || previous?.username || '',
      });
    }
    profiles = [...merged.values()].filter((item) => USERNAME_RE.test(item.username))
      .sort((a, b) => a.publicId.localeCompare(b.publicId));
  } else {
    console.warn('[public-profiles] unexpected API payload; keeping committed snapshot');
  }
} catch (error) {
  console.warn(`[public-profiles] API unavailable, keeping committed snapshot: ${error.message}`);
}

const body = `/**
 * self-generated by scripts/fetch-public-profiles.mjs — ویرایش دستی نکنید.
 * فهرست کدهای پایدار و نامهای کاربری برای ساخت مسیرهای ایستا.
 */
export interface PublicProfileSnapshotEntry {
  publicId: string;
  username: string;
}

export const PUBLIC_PROFILES: readonly PublicProfileSnapshotEntry[] = ${JSON.stringify(profiles, null, 2)};
`;

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, body, 'utf8');
console.log(`[public-profiles] wrote ${profiles.length} profiles to ${OUTPUT}`);
